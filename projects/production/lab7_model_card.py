"""Lab 7 - write a model card and a dataset card, then audit them.

The cards are generated from measurements rather than typed by hand, and then
checked in two directions:

1. **Structure** - every required section is present.
2. **Claims** - every number in the prose traces back to a measurement file.

Neither check makes a card honest. They make a *dishonest* card harder to write
by accident, which is most of what documentation tooling can do. The lab ends by
tampering with a card and watching the audit catch it, because a check you have
never seen fail is a check you do not know works.

    python lab7_model_card.py
    python lab7_model_card.py --selftest
"""

from __future__ import annotations

import sys
from datetime import date
from pathlib import Path

import numpy as np
from sklearn.linear_model import LogisticRegression

sys.path.insert(0, str(Path(__file__).resolve().parent))

from eval_core import (  # noqa: E402
    Checks,
    Report,
    base_parser,
    claims_audit,
    data,
    environment_snapshot,
    expected_calibration_error,
    macro_f1,
    manifest_status,
    measured_footer,
    metrics,
    render_dataset_card,
    render_model_card,
    sha256_file,
    stratified_split,
    validate_card,
    write_json,
    DATASET_CARD_SECTIONS,
    MODEL_CARD_SECTIONS,
)

OUT_DIR = data.ROOT / "outputs" / "production" / "lab7"
NUMERIC = ["tenure_months", "monthly_charges", "support_tickets", "usage_gb"]
CATEGORICAL = ["contract_type", "region"]
SEED = 7
TODAY = date.today().isoformat()


def measure() -> tuple[dict, dict, dict]:
    data.ensure_data()
    rows = data.load_csv(data.DATA / "customers" / "customers.csv")
    train, _, test = stratified_split(rows, "churned", (0.7, 0.15, 0.15), seed=SEED)
    x_train, _, levels = data.feature_matrix(train, NUMERIC, CATEGORICAL)
    x_test, _, _ = data.feature_matrix(test, NUMERIC, CATEGORICAL, levels)
    y_train = np.array(data.target(train))
    y_test = np.array(data.target(test))

    model = LogisticRegression(max_iter=2000, random_state=SEED).fit(x_train, y_train)
    probs = model.predict_proba(x_test)[:, 1]
    preds = (probs >= 0.5).astype(int)
    prf = metrics.precision_recall_f1(y_test, preds)

    card_metrics = {
        "test_rows": int(len(y_test)),
        "accuracy": metrics.accuracy(y_test, preds),
        "macro_f1": macro_f1(y_test, preds),
        "precision": prf["precision"],
        "recall": prf["recall"],
        "auc": metrics.roc_auc(y_test, probs),
        "ece": expected_calibration_error(y_test, probs),
        "seed": SEED,
    }

    dataset_stats = {
        "rows": len(rows),
        "columns": 10,
        "composition": (
            f"{sum(1 for row in rows if row['churned'] == 1)} churned and "
            f"{sum(1 for row in rows if row['churned'] == 0)} retained rows; "
            f"{sum(1 for row in rows if row['customer_id'].endswith('-DUP'))} duplicate rows; "
            f"regions {sorted({row['region'] for row in rows})}."
        ),
    }
    return card_metrics, dataset_stats, {"rows": rows, "test_rows": len(test)}


def cards() -> tuple[str, str, dict]:
    card_metrics, dataset_stats, _ = measure()
    status = manifest_status()
    dataset_digest = sha256_file(data.DATA / "manifest.json")

    model_meta = {
        "name": "churn-logistic-v1",
        "version": "1.0.0",
        "type": "binary logistic regression over 11 engineered features",
        "owner": "AITopics teaching team",
        "created": TODAY,
        "digest": dataset_digest[:16],
        "intended_use": (
            "Rank existing subscribers by churn risk so a retention team can prioritise outreach. "
            "Scores are advisory; no adverse decision is automated."
        ),
        "out_of_scope": (
            "Not for pricing, credit, eligibility, or employment decisions. Not validated outside the "
            "synthetic data described in the dataset card. Not a forecast of individual behaviour."
        ),
        "training_data": (
            f"Synthetic subscription records generated by `scripts/make_eval_data.py` (seed {status['seed']}, "
            f"{status['files']} files, manifest digest `{dataset_digest[:16]}`). No real customer data was used."
        ),
        "limitations": [
            "Trained on synthetic data; the relationship between features and churn is imposed by the generator.",
            "Labels contain deliberate noise, so no model can reach perfect accuracy on this data.",
            "The 30% base rate is a property of the generator, not of any real customer base.",
            "Not recalibrated for a different population; calibration error is reported for this test set only.",
        ],
        "ethical": [
            "Retention outreach can be intrusive; contact decisions stay with humans.",
            "Features are behavioural and billing attributes, not protected characteristics.",
            "No individual-level explanation is provided; do not present a score as a reason.",
        ],
        "licence": "Code MIT; generated data CC0, as described in the repository README.",
    }

    dataset_meta = {
        "name": "synthetic-subscription-churn",
        "version": "1.0.0",
        "format": "CSV (customers.csv) plus a JSON manifest",
        "digest": dataset_digest[:16],
        "provenance": (
            "Generated locally by `scripts/make_eval_data.py` from seed "
            f"{status['seed']}. No third-party source, no scraping, no personal data."
        ),
        "collection": (
            "Not collected. Values are drawn from simple distributions and a logistic churn function; "
            "duplicate rows are inserted on purpose to support the leakage lab."
        ),
        "preprocessing": (
            "Categorical fields are one-hot encoded against training-set levels. Numeric fields are used "
            "as generated; no imputation is required because no field is missing."
        ),
        "uses": "Teaching evaluation, leakage detection, calibration, and model comparison.",
        "limitations": [
            "Not a sample of any real population.",
            "Contains two leaky columns (account_status, cancellation_reason) on purpose.",
            "3% of rows are duplicates of other rows, identified by a -DUP suffix.",
        ],
        "licence": "CC0 1.0 (generated data).",
    }
    return render_model_card(model_meta, card_metrics), render_dataset_card(dataset_meta, dataset_stats), card_metrics


def run() -> dict:
    model_card, dataset_card, card_metrics = cards()
    model_check = validate_card(model_card, MODEL_CARD_SECTIONS)
    dataset_check = validate_card(dataset_card, DATASET_CARD_SECTIONS)
    # Counts that live in the card but not in the metrics dict: rows, columns,
    # duplicate rate, feature count, and the generator's base rate.
    extra = [card_metrics["test_rows"], 1854, 10, 3, 11, 30]
    audit = claims_audit(model_card, card_metrics, extra_allowed=extra)

    tampered = model_card.replace(
        "## Limitations",
        "The model reaches 0.97 accuracy on unseen customers.\n\n## Limitations",
    )
    tampered_audit = claims_audit(tampered, card_metrics, extra_allowed=extra)

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUT_DIR / "model-card.md").write_text(model_card, encoding="utf-8")
    (OUT_DIR / "dataset-card.md").write_text(dataset_card, encoding="utf-8")
    write_json(OUT_DIR, "metrics.json", {"model": card_metrics, "environment": environment_snapshot()})

    return {
        "model_card": model_card,
        "dataset_card": dataset_card,
        "model_check": model_check,
        "dataset_check": dataset_check,
        "audit": audit,
        "tampered_audit": tampered_audit,
        "metrics": card_metrics,
        "environment": environment_snapshot(),
    }


def build_report(result: dict) -> Report:
    report = Report(
        "Lab 7 - model card and dataset card",
        "Generated from measurements, then checked for structure and for unsupported numbers.",
    )
    report.heading("Structure check")
    report.table(
        [
            {"card": "model", "complete": result["model_check"]["ok"],
             "missing": ", ".join(result["model_check"]["missing"]) or "none"},
            {"card": "dataset", "complete": result["dataset_check"]["ok"],
             "missing": ", ".join(result["dataset_check"]["missing"]) or "none"},
        ],
        ["card", "complete", "missing"],
    )

    report.heading("Claims audit")
    report.text(
        f"Numbers in the model card that are not traceable to a measured value: "
        f"{len(result['audit']['unsupported'])}. Every metric quoted in the Evaluation table comes from the "
        "same run that produced this report."
    )

    report.heading("Tampered card")
    report.text(
        "A sentence claiming 0.97 accuracy was inserted before the Limitations section. The audit reported:"
    )
    report.table(
        [{"number": item["number"], "line": item["line"]} for item in result["tampered_audit"]["unsupported"]]
        or [{"number": "none", "line": "audit failed to notice a fabricated metric"}],
        ["number", "line"],
    )
    report.text(
        "This is a weak guarantee. The audit catches invented *numbers*, not invented framing, missing "
        "limitations, or a metric measured on the wrong split. Read the card as an argument, not a certificate."
    )

    report.heading("Generated model card")
    report.text(result["model_card"])
    report.heading("Generated dataset card")
    report.text(result["dataset_card"])
    return report


def selftest() -> int:
    checks = Checks("lab 7 - model and dataset cards")
    result = run()

    checks.check("model card has every required section", result["model_check"]["ok"],
                 str(result["model_check"]["missing"]))
    checks.check("dataset card has every required section", result["dataset_check"]["ok"],
                 str(result["dataset_check"]["missing"]))
    checks.check("generated card passes its own claims audit", result["audit"]["ok"],
                 str(result["audit"]["unsupported"]))
    checks.check("tampered card is caught", not result["tampered_audit"]["ok"])
    checks.check("the fabricated number is named",
                 any(item["number"] == "0.97" for item in result["tampered_audit"]["unsupported"]),
                 str(result["tampered_audit"]["unsupported"]))
    checks.check("card states intended use", "## Intended use" in result["model_card"])
    checks.check("card states out-of-scope use", "## Out-of-scope use" in result["model_card"])
    checks.check("card records limitations", "synthetic" in result["model_card"])
    checks.check("dataset card records provenance and licence",
                 "## Provenance" in result["dataset_card"] and "## Licence" in result["dataset_card"])
    checks.check("metrics file written", (OUT_DIR / "metrics.json").exists())
    checks.check("cards written for review",
                 (OUT_DIR / "model-card.md").exists() and (OUT_DIR / "dataset-card.md").exists())

    report = build_report(result)
    path = report.write(OUT_DIR, "report.md", measured_footer(result["environment"]))
    checks.check("report written", path.exists() and path.stat().st_size > 1500)
    return checks.report()


def main() -> int:
    parser = base_parser(__doc__ or "")
    args = parser.parse_args()
    if args.selftest:
        return selftest()
    result = run()
    print(build_report(result).render(measured_footer(result["environment"])))
    print(f"\nwritten: {OUT_DIR}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
