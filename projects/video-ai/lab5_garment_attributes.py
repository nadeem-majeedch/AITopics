"""Lab 5 - Clothing attribute recognition: a narrow label set, and the table that keeps it honest.

Goal: build a two-headed classifier that answers two observable questions about a garment -
*what kind of garment is it* and *what colour is it* - and then measure how the answers change
when the picture gets worse.

Three things this lab is careful about, because they are the parts that go wrong in real
retail and security projects:

1. **The label set is narrow and observable.** Four categories (shirt, trousers, jacket, hat)
   and six colours. Every label is something two people can agree on by looking. There is no
   output for gender, age, ethnicity, body shape, health, or identity, and no code path that
   could produce one; :func:`video_core.garments.sensitive_attribute_statement` says why.
2. **Clean accuracy is the least interesting number.** A two-head CNN reaches 1.00 on clean
   synthetic garments. The table that matters is the perturbation sweep: dim the lights, put
   a shopping bag in front of the garment, change the background - and watch the colour head
   fall apart first, because colour is exactly the thing lighting changes.
3. **Data provenance is part of the method.** The images here are generated by code (CC0).
   Module 10 and the lab manual explain how to swap in a licensed dataset (DeepFashion) and
   what documentation a consented collection needs.

This is a frame-level image model used on still crops, not a video model: the pipeline that
produces the crops from video is Lab 7's job, and the identity-linkage risk of doing so is
Module 15's subject. A clothing classifier is not a person re-identification system, and this
lab does not build one.

Run:

    python lab5_garment_attributes.py               # ~10 s on CPU
    python lab5_garment_attributes.py --selftest    # documented run, checks only
    python lab5_garment_attributes.py --per-class 80 --epochs 30

Output:

    outputs/lab5_garments.png          test grid: image, true label, prediction
    outputs/lab5_garment_attributes.json
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import cv2
import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))

import lab_support as support
from video_core import garments, synth, video

TRAIN_SEED = 3
TEST_SEED = 107


def to_display(images: np.ndarray) -> list[np.ndarray]:
    """float32 [0,1] NHWC -> list of uint8 BGR frames ready for drawing."""
    out = []
    for image in images:
        arr = np.clip(garments.as_float01(image) * 255.0, 0, 255).astype(np.uint8)
        out.append(arr)
    return out


def save_grid(images: np.ndarray, categories: np.ndarray, colours: np.ndarray,
              cat_pred: np.ndarray, col_pred: np.ndarray, path: Path) -> Path:
    """A contact sheet where each tile is captioned with truth and prediction."""
    labels = []
    for i in range(len(images)):
        truth = f"{synth.GARMENT_CATEGORIES[categories[i]]}/{synth.GARMENT_COLOURS[colours[i]]}"
        guess = f"{synth.GARMENT_CATEGORIES[cat_pred[i]]}/{synth.GARMENT_COLOURS[col_pred[i]]}"
        mark = "" if (categories[i] == cat_pred[i] and colours[i] == col_pred[i]) else " WRONG"
        labels.append(f"{truth} -> {guess}{mark}")
    sheet = video.contact_sheet(to_display(images[:12]), cols=4, labels=labels[:12])
    support.OUT.mkdir(parents=True, exist_ok=True)
    cv2.imwrite(str(path), sheet)
    return path


def print_confusion(report: dict, names: list[str]) -> None:
    print("      " + "".join(f"{name[:9]:>10s}" for name in names) + "   (rows = truth)")
    for i, name in enumerate(names):
        row = "".join(f"{value:>10d}" for value in report["confusion"][i])
        print(f"  {name[:9]:>9s}{row}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--per-class", type=int, default=60,
                        help="training images per garment category (default 60)")
    parser.add_argument("--test-per-class", type=int, default=15)
    parser.add_argument("--epochs", type=int, default=25)
    parser.add_argument("--selftest", action="store_true", help="small run, checks only")
    args = parser.parse_args()

    # The checks assert accuracy above 0.85 against the documented training
    # configuration. A shrunken run (30 images per class, 12 epochs) lands near
    # chance and fails them, so the smoke test trains the documented size; it
    # takes a few seconds either way.
    per_class = args.per_class
    epochs = args.epochs
    test_per_class = args.test_per_class

    support.rule("label set")
    print(f"  categories : {list(synth.GARMENT_CATEGORIES)}")
    print(f"  colours    : {list(synth.GARMENT_COLOURS)}")
    print("  licence    : CC0-1.0, generated by video_core.synth (no people, no photos)")
    print("  not modelled: gender, age, ethnicity, body shape, health, identity")

    support.rule("data")
    x_train, y_cat, y_col = synth.garment_dataset(n_per_class=per_class, seed=TRAIN_SEED)
    x_test, t_cat, t_col = synth.garment_dataset(n_per_class=test_per_class, seed=TEST_SEED)
    print(f"  train      : {len(x_train)} images, seed {TRAIN_SEED}")
    print(f"  test       : {len(x_test)} images, seed {TEST_SEED} (disjoint seeds, so no")
    print("               test image shares its random draw with a training image)")
    print(f"  shape      : {x_train.shape[1:]} RGB, float [0,1]")
    print(f"  balance    : per-category {np.bincount(y_cat).tolist()}, "
          f"per-colour {np.bincount(y_col).tolist()}")

    support.rule("training")
    model, history = garments.train_garment_model(x_train, y_cat, y_col, epochs=epochs, log=True)
    print(f"  parameters : {sum(p.numel() for p in model.parameters()):,}")
    print(f"  loss       : {history['loss'][0]} -> {history['loss'][-1]}")

    support.rule("clean test set")
    cat_pred, col_pred = garments.predict_garments(model, x_test)
    cat_report = garments.category_report(t_cat, cat_pred)
    col_report = garments.colour_report(t_col, col_pred)
    print(f"  category   : accuracy {cat_report['accuracy']:.3f}  "
          f"macro F1 {cat_report['macro_f1']:.3f}")
    support.table([{"class": k, **v} for k, v in cat_report["per_class"].items()],
                  ["class", "precision", "recall", "f1", "support"])
    print_confusion(cat_report, list(synth.GARMENT_CATEGORIES))
    print(f"\n  colour     : accuracy {col_report['accuracy']:.3f}  "
          f"macro F1 {col_report['macro_f1']:.3f}")
    support.table([{"class": k, **v} for k, v in col_report["per_class"].items()],
                  ["class", "precision", "recall", "f1", "support"])
    confusions = garments.class_confusions(t_cat, cat_pred, list(synth.GARMENT_CATEGORIES))
    print(f"  mistakes   : {confusions or 'none on the clean test set'}")

    support.rule("robustness: one factor at a time")
    sweep = garments.robustness_sweep(model, x_test, t_cat, t_col)
    support.table(sweep, ["condition", "category_acc", "colour_acc"])
    clean = sweep[0]
    worst = min(sweep, key=lambda row: row["colour_acc"])
    print(f"  colour survives a bright shop and dies in a dim one "
          f"({clean['colour_acc']:.2f} -> {worst['colour_acc']:.2f} under "
          f"'{worst['condition']}').")
    print("  Category is more robust than colour because shape survives resampling and")
    print("  blur, while a colour measurement is a brightness measurement. If a project")
    print("  needs colour, it needs colour correction before the classifier, not a bigger")
    print("  classifier after it.")

    grid = save_grid(x_test, t_cat, t_col, cat_pred, col_pred, support.OUT / "lab5_garments.png")
    print(f"\n  grid       : {grid.name}")

    support.rule("responsible scope")
    print("  " + garments.sensitive_attribute_statement())

    results = [
        support.check("category accuracy above 0.85 on clean images",
                      cat_report["accuracy"] >= 0.85, f"{cat_report['accuracy']:.3f}"),
        support.check("colour accuracy above 0.85 on clean images",
                      col_report["accuracy"] >= 0.85, f"{col_report['accuracy']:.3f}"),
        support.check("every category appears in the test set",
                      len(set(t_cat.tolist())) == len(synth.GARMENT_CATEGORIES)),
        support.check("degradation is reported, not hidden",
                      worst["colour_acc"] < clean["colour_acc"],
                      f"{clean['colour_acc']:.2f} -> {worst['colour_acc']:.2f}"),
        support.check("the model exposes exactly two heads (no identity output)",
                      len(list(model.children())) == 3),
        support.check("grid written", grid.exists() and grid.stat().st_size > 0, grid.name),
    ]

    support.write_report("lab5_garment_attributes.json", {
        "lab": "clothing attribute recognition",
        "labels": {"categories": list(synth.GARMENT_CATEGORIES),
                   "colours": list(synth.GARMENT_COLOURS)},
        "data": {"train": len(x_train), "test": len(x_test),
                 "train_seed": TRAIN_SEED, "test_seed": TEST_SEED},
        "parameters": int(sum(p.numel() for p in model.parameters())),
        "history": history,
        "category": cat_report,
        "colour": col_report,
        "confusions": confusions,
        "robustness": sweep,
        "scope": garments.sensitive_attribute_statement(),
        "checks": results,
    })
    return support.all_checks(results)


if __name__ == "__main__":
    raise SystemExit(main())
