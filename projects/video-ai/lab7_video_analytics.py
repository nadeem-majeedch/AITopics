"""Lab 7 - A configurable video analytics application, with the error handling that matters.

Goal: assemble the pieces from Labs 2-6 into one program that takes a video, runs detection
and optional tracking, counts crossings, writes an annotated video and a summary document -
and that fails *well* when the input is rubbish.

The last part is the point of the lab. In the earlier labs the data always loads, because the
data was generated by the same repository. A real tool is pointed at whatever the user has:
a phone video with no index, a download that stopped at 60% of a file, a `.mp4` that is
actually an HTML error page, a clip recorded at 120 fps, a four-second clip with nothing in
it. Each of those must produce a clear message and a non-zero exit code, not a traceback and
not a silent empty output video.

The configuration is a JSON file (``configs/video_analytics.json``) so the same program can
be re-pointed without editing code, which is what makes it a tool instead of a script.

Run:

    python lab7_video_analytics.py                              # default config
    python lab7_video_analytics.py --video street_crowd --stride 2
    python lab7_video_analytics.py --config configs/video_analytics.json --no-tracking
    python lab7_video_analytics.py --selftest                   # error-handling scenarios

Exit codes: 0 success, 2 bad input (missing / corrupt / undecodable / zero frames),
3 bad config. Nothing is written on a failed run, so a summary file on disk always
belongs to a completed analysis.

Output:

    outputs/lab7_analytics.mp4    annotated video
    outputs/lab7_summary.json     counts, rate, per-frame statistics, warnings
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

import cv2
import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))

import lab_support as support
from video_core import counting, detect, metrics, tracking, video

DEFAULTS = {
    "video": "street_day",
    "stride": 1,
    "limit": None,
    "model": "tiny",
    "score_threshold": 0.5,
    "nms_iou": 0.3,
    "tracking": {"enabled": True, "max_age": 6, "min_hits": 2, "iou_threshold": 0.3},
    "counting": {"enabled": True,
                 "line": {"kind": "vertical", "at": 0.55, "anchor": "bottom"}},
    "output": {"video": "outputs/lab7_analytics.mp4",
               "summary": "outputs/lab7_summary.json",
               "fourcc": "mp4v",
               "draw_trails": True},
    "runtime": {"warn_below_fps": 5.0, "max_frames_without_detection": 30},
}


class ConfigError(RuntimeError):
    """Raised when the configuration file cannot be used as written."""


def merge(base: dict, override: dict) -> dict:
    """Recursive merge; the override wins, unknown keys are kept so they can be reported."""
    out = dict(base)
    for key, value in override.items():
        if isinstance(value, dict) and isinstance(out.get(key), dict):
            out[key] = merge(out[key], value)
        else:
            out[key] = value
    return out


def check_keys(config: dict, template: dict, path: str = "") -> list[str]:
    """Warn about keys the program will ignore - the most common config mistake."""
    warnings = []
    for key, value in config.items():
        if key.startswith("_"):
            continue
        if key not in template:
            warnings.append(f"unknown config key {path}{key!r} (ignored)")
        elif isinstance(value, dict) and isinstance(template[key], dict):
            warnings.extend(check_keys(value, template[key], f"{path}{key}."))
    return warnings


def load_config(path: Path | None, cli: dict) -> tuple[dict, list[str]]:
    config = json.loads(json.dumps(DEFAULTS))
    warnings: list[str] = []
    if path is not None:
        if not path.exists():
            raise ConfigError(f"config file not found: {path}")
        try:
            payload = json.loads(path.read_text(encoding="utf-8"))
        except json.JSONDecodeError as exc:
            raise ConfigError(f"{path} is not valid JSON: {exc}") from exc
        if not isinstance(payload, dict):
            raise ConfigError(f"{path} must contain a JSON object")
        warnings.extend(check_keys(payload, DEFAULTS))
        config = merge(config, payload)
    for key, value in cli.items():
        if value is not None:
            if isinstance(value, dict) and isinstance(config.get(key), dict):
                config[key] = merge(config[key], value)
            else:
                config[key] = value
    return config, warnings


def resolve_video(value: str) -> Path:
    """Accept a path, or the name of a generated scene."""
    path = Path(value)
    if path.exists():
        return path
    try:
        return support.video_path(value)
    except KeyError as exc:
        raise video.VideoError(value, "not a file and not a known scene name") from exc


def line_points(line: dict, width: int, height: int) -> tuple[tuple[float, float],
                                                              tuple[float, float]]:
    """Turn the config's line description into two points in pixel space."""
    kind = line.get("kind", "vertical")
    at = float(line.get("at", 0.55))
    if not 0.0 < at < 1.0:
        raise ConfigError(f"counting.line.at must be between 0 and 1, got {at}")
    if kind == "vertical":
        x = at * width
        return (x, 0.0), (x, float(height))
    if kind == "horizontal":
        y = at * height
        return (0.0, y), (float(width), y)
    raise ConfigError(f"counting.line.kind must be 'vertical' or 'horizontal', got {kind!r}")


def run(config: dict) -> tuple[dict, int]:
    """Execute the pipeline. Returns ``(summary, exit_code)``."""
    started = time.perf_counter()
    source = resolve_video(str(config["video"]))
    info = video.probe(source, count_frames=True)
    if info.frame_count == 0:
        raise video.VideoError(source, "no decodable frames")
    if info.fps <= 0:
        raise video.VideoError(source, "no frame rate in the header",
                               "the analyser needs a rate to compute timestamps and rates")

    warnings: list[str] = []
    aspect = info.width / max(info.height, 1)
    if abs(aspect - 16 / 9) > 0.02:
        warnings.append(f"unusual aspect ratio {aspect:.2f}; boxes are still in pixel "
                        "coordinates, check them before trusting counts")

    model_name = str(config.get("model", "tiny")).lower()
    if model_name == "tiny":
        model, model_info = support.train_tiny_detector()
        model_label = "TinyDetector (trained in-section)"
    elif model_name in {"ssdlite", "coco"}:
        model, model_info = support.ssdlite(float(config["score_threshold"]))
        if not model_info["available"]:
            raise video.VideoError(source, "pretrained weights unavailable",
                                   str(model_info["load_error"]))
        model_label = "SSDLite320 (COCO-pretrained)"
        warnings.append("the COCO model predicts COCO labels; counts are near zero on "
                        "footage that does not look like COCO")
    else:
        raise ConfigError(f"model must be 'tiny' or 'ssdlite', got {model_name!r}")

    track_cfg = config["tracking"]
    count_cfg = config["counting"]
    tracker = (tracking.IoUTracker(iou_threshold=float(track_cfg.get("iou_threshold", 0.3)),
                                   max_age=int(track_cfg.get("max_age", 6)),
                                   min_hits=int(track_cfg.get("min_hits", 2)))
               if track_cfg.get("enabled", True) else None)
    counter = None
    if count_cfg.get("enabled", True):
        p1, p2 = line_points(count_cfg.get("line", {}), info.width, info.height)
        counter = counting.LineCounter(p1, p2, anchor=count_cfg.get("line", {}).get("anchor",
                                                                                    "bottom"))

    out_cfg = config["output"]
    out_path = support.HERE / str(out_cfg["video"])
    out_path.parent.mkdir(parents=True, exist_ok=True)
    fourcc = str(out_cfg.get("fourcc", "mp4v"))
    if fourcc not in video.SUPPORTED_FOURCC:
        raise ConfigError(f"fourcc {fourcc!r} is not supported here; use one of "
                          f"{sorted(video.SUPPORTED_FOURCC)}")

    stride = max(1, int(config.get("stride", 1)))
    limit = config.get("limit")
    detect_times: list[float] = []
    frames_out = 0
    total_detections = 0
    frames_since_detection = 0
    longest_dry_spell = 0
    history: dict[int, list[tuple[float, float]]] = {}

    with video.VideoWriter(out_path, info.fps / stride, (info.width, info.height),
                           fourcc) as writer:
        for index, stamp, frame in video.iter_frames(source, stride=stride, limit=limit):
            t0 = time.perf_counter()
            detections = model.predict(frame, score_threshold=float(config["score_threshold"]),
                                       nms_iou=float(config["nms_iou"]))
            detect_times.append(time.perf_counter() - t0)
            total_detections += len(detections)
            frames_since_detection = 0 if detections else frames_since_detection + 1
            longest_dry_spell = max(longest_dry_spell, frames_since_detection)

            if tracker is not None:
                tracks = tracker.update(detections)
                drawn_tracks = [{"track_id": t.track_id, "box": list(t.box),
                                 "label": t.label, "class": t.label_name}
                                for t in tracker.tracks
                                if t.hits >= tracker.min_hits]
                if counter is not None:
                    counter.update(drawn_tracks, frames_out)
                boxes = [t["box"] for t in drawn_tracks]
                captions = [f"#{t['track_id']} {t['class']}" for t in drawn_tracks]
                for t in drawn_tracks:
                    x1, y1, x2, y2 = t["box"]
                    trail = history.setdefault(int(t["track_id"]), [])
                    trail.append(((x1 + x2) / 2, (y1 + y2) / 2))
                    if len(trail) > 16:
                        trail.pop(0)
            else:
                boxes = [d.box for d in detections]
                captions = [d.label_name for d in detections]
                drawn_tracks = []

            drawn = frame
            if out_cfg.get("draw_trails", True) and history:
                drawn = video.draw_trails(drawn, list(history.values()))
            if counter is not None:
                cv2.line(drawn, (int(counter.p1[0]), int(counter.p1[1])),
                         (int(counter.p2[0]), int(counter.p2[1])), (0, 215, 255), 2)
                cv2.putText(drawn, f"count {len(counter.events)}", (8, 22),
                            cv2.FONT_HERSHEY_SIMPLEX, 0.6, (0, 215, 255), 2)
            drawn = video.annotate_frame(drawn, boxes, captions)
            cv2.putText(drawn, f"frame {index} t={stamp:.1f}s", (8, info.height - 10),
                        cv2.FONT_HERSHEY_SIMPLEX, 0.45, (240, 240, 240), 1)
            writer.write(drawn)
            frames_out += 1

    if frames_out == 0:
        raise video.VideoError(source, "no frames survived decoding with this stride",
                              f"stride={stride}, limit={limit}")
    if out_path.stat().st_size == 0:
        raise video.VideoError(out_path, "annotated video is empty")

    duration = frames_out * stride / info.fps
    mean_detect_ms = float(np.mean(detect_times)) * 1000
    processed_fps = 1000.0 / mean_detect_ms if mean_detect_ms else float("inf")
    if processed_fps < float(config["runtime"]["warn_below_fps"]):
        warnings.append(f"detection runs at {processed_fps:.1f} fps, below the configured "
                        f"floor of {config['runtime']['warn_below_fps']} fps")
    if longest_dry_spell >= int(config["runtime"]["max_frames_without_detection"]):
        warnings.append(f"{longest_dry_spell} consecutive processed frames had no "
                        "detections - the model may not suit this footage")

    counts = counter.tally() if counter else {}
    summary = {
        "input": {
            "file": str(source),
            "width": info.width, "height": info.height, "fps": round(info.fps, 3),
            "frames_decoded": info.frame_count, "duration_s": round(info.duration_s, 3),
            "fourcc": info.fourcc, "codec_note": info.codec_note,
            "bytes": source.stat().st_size,
        },
        "processing": {
            "stride": stride, "frames_processed": frames_out,
            "processed_duration_s": round(duration, 3),
            "model": model_label,
            "score_threshold": config["score_threshold"],
            "nms_iou": config["nms_iou"],
            "tracking": bool(track_cfg.get("enabled", True)),
            "counting": bool(counter),
            "mean_detect_ms": round(mean_detect_ms, 2),
            "processed_fps": round(processed_fps, 2),
            "real_time_factor": round(frames_out / max(info.fps * duration, 1e-9), 3),
            "wall_seconds": round(time.perf_counter() - started, 2),
        },
        "detections": {
            "total": total_detections,
            "per_processed_frame": round(total_detections / frames_out, 3),
            "longest_run_without_detection": longest_dry_spell,
        },
        "counting": {
            "counts": counts,
            "total": len(counter.events) if counter else 0,
            "events": counter.events_as_dicts() if counter else [],
            "flow": counting.flow_summary(counts, duration_s=duration) if counter else {},
            "line": {"p1": list(counter.p1), "p2": list(counter.p2),
                     "anchor": counter.anchor} if counter else None,
        },
        "tracking": {
            # Every track that was drawn, i.e. every identity this run produced. It is not a
            # vehicle count: one vehicle can account for several tracks (Module 7).
            "unique_tracks_drawn": len(history),
        },
        "output": {"video": str(out_path), "bytes": out_path.stat().st_size},
        "warnings": warnings,
        "model_info": {k: v for k, v in model_info.items() if k != "history"},
    }

    summary_path = support.HERE / str(out_cfg["summary"])
    summary_path.parent.mkdir(parents=True, exist_ok=True)
    summary_path.write_text(json.dumps(summary, indent=2, default=str) + "\n",
                            encoding="utf-8")
    return summary, 0


def make_bad_inputs(directory: Path) -> list[tuple[str, Path, str]]:
    """Create the malformed inputs this lab tests against. Each is a real failure mode."""
    directory.mkdir(parents=True, exist_ok=True)
    good = support.video_path("street_day")

    truncated = directory / "truncated.mp4"
    truncated.write_bytes(good.read_bytes()[: good.stat().st_size // 3])

    fake = directory / "html_error.mp4"
    fake.write_text("<html><body>404 Not Found</body></html>\n", encoding="utf-8")

    empty = directory / "empty.mp4"
    empty.write_bytes(b"")

    # A video whose bytes are fine but whose name says .txt: OpenCV/FFmpeg here dispatches on
    # the extension and refuses it. Worth keeping as a case, because "the file is a valid
    # video" and "the tool will open it" are different claims.
    mislabelled = directory / "actually_a_video.txt"
    mislabelled.write_bytes(good.read_bytes()[: 200 * 1024])

    return [
        ("missing file", directory / "does_not_exist.mp4", "missing"),
        ("truncated", truncated, "truncated"),
        ("not a video", fake, "fake"),
        ("empty file", empty, "empty"),
        ("video bytes, .txt name", mislabelled, "mislabelled"),
        ("a good video", good, "valid"),
    ]


def selftest() -> int:
    support.rule("error handling")
    directory = support.OUT / "bad_inputs"
    rows = []
    results = []
    for label, path, kind in make_bad_inputs(directory):
        config, _ = load_config(None, {"video": str(path), "limit": 10})
        try:
            summary, code = run(config)
            outcome = f"ok, {summary['processing']['frames_processed']} frames"
            rows.append({"case": label, "exit": code, "outcome": outcome})
            if kind == "valid":
                results.append(support.check(
                    "a good video runs and produces frames",
                    summary["processing"]["frames_processed"] > 0,
                    f"{summary['processing']['frames_processed']} frames"))
        except video.VideoError as exc:
            rows.append({"case": label, "exit": 2, "outcome": exc.reason})
            results.append(support.check(f"{label}: rejected with a clear reason",
                                         bool(exc.reason), exc.reason))
        except ConfigError as exc:
            rows.append({"case": label, "exit": 3, "outcome": str(exc)})
            results.append(support.check(f"{label}: config error", False, str(exc)))
    support.table(rows, ["case", "exit", "outcome"])

    support.rule("bad configuration")
    bad_config = support.OUT / "bad_config.json"
    bad_config.write_text('{"model": "yolo9000", "tracking": {"max_age": "six"}}',
                          encoding="utf-8")
    try:
        config, warnings = load_config(bad_config, {})
        run(config)
        results.append(support.check("unknown model name rejected", False))
    except ConfigError as exc:
        print(f"  rejected: {exc}")
        results.append(support.check("unknown model name rejected with a message", True,
                                     str(exc)[:40]))
    print(f"  warnings from the config: {warnings}")

    support.rule("a real run")
    config, _ = load_config(support.HERE / "configs" / "video_analytics.json", {"limit": 30})
    summary, code = run(config)
    print(f"  processed  : {summary['processing']['frames_processed']} frames at "
          f"{summary['processing']['processed_fps']} fps")
    print(f"  detections : {summary['detections']['total']} "
          f"({summary['detections']['per_processed_frame']}/frame)")
    print(f"  counted    : {summary['counting']['total']} crossings")
    print(f"  warnings   : {summary['warnings'] or 'none'}")
    results.append(support.check("real run exits 0", code == 0))
    results.append(support.check("summary written", (support.HERE / str(
        config["output"]["summary"])).exists()))
    results.append(support.check("annotated video readable",
                                 (support.HERE / str(config["output"]["video"])).exists()))
    return support.all_checks(results)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--config", default="configs/video_analytics.json")
    parser.add_argument("--video", default=None, help="path or generated scene name")
    parser.add_argument("--stride", type=int, default=None)
    parser.add_argument("--limit", type=int, default=None)
    parser.add_argument("--model", default=None, choices=["tiny", "ssdlite"])
    parser.add_argument("--score", type=float, default=None, dest="score_threshold")
    parser.add_argument("--no-tracking", action="store_true")
    parser.add_argument("--selftest", action="store_true")
    args = parser.parse_args()

    if args.selftest:
        return selftest()

    cli = {"video": args.video, "stride": args.stride, "limit": args.limit,
           "model": args.model, "score_threshold": args.score_threshold}
    if args.no_tracking:
        cli["tracking"] = {"enabled": False}
        cli["counting"] = {"enabled": False}

    try:
        config_path = support.HERE / args.config if args.config else None
        config, warnings = load_config(config_path if config_path and config_path.exists()
                                       else None, cli)
        support.rule(f"analysing {config['video']}")
        print(f"  config     : {config_path}")
        for warning in warnings:
            print(f"  warning    : {warning}")
        summary, code = run(config)
    except ConfigError as exc:
        print(f"config error: {exc}", file=sys.stderr)
        return 3
    except video.VideoError as exc:
        print(f"input error: {exc.reason}", file=sys.stderr)
        if exc.detail:
            print(f"  detail: {exc.detail}", file=sys.stderr)
        print("  the analyser stopped before writing any output", file=sys.stderr)
        return 2

    p = summary["processing"]
    print(f"  input      : {summary['input']['width']}x{summary['input']['height']}, "
          f"{summary['input']['fps']} fps, {summary['input']['frames_decoded']} frames, "
          f"{summary['input']['fourcc']}")
    print(f"  processed  : {p['frames_processed']} frames (stride {p['stride']}) in "
          f"{p['wall_seconds']} s")
    print(f"  speed      : {p['mean_detect_ms']} ms/frame -> {p['processed_fps']} fps")
    print(f"  detections : {summary['detections']['total']}")
    print(f"  counted    : {summary['counting']['total']} crossings "
          f"{summary['counting']['counts']}")
    print(f"  flow       : {summary['counting']['flow'].get('per_hour')} per hour "
          "(extrapolated)")
    print(f"  video      : {summary['output']['video']}")
    print(f"  summary    : {config['output']['summary']}")
    for warning in summary["warnings"]:
        print(f"  warning    : {warning}")
    print(f"\n  all checks passed: exit {code}")
    return code


if __name__ == "__main__":
    raise SystemExit(main())
