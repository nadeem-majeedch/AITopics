GARMENT_CATEGORIES = ("shirt", "trousers", "jacket", "hat")
GARMENT_COLOURS = ("red", "blue", "green", "black", "white", "yellow")

_COLOUR_BGR = {
    "red": (40, 40, 200),
    "blue": (200, 90, 40),
    "green": (50, 160, 60),
    "black": (28, 28, 30),
    "white": (225, 225, 228),
    "yellow": (40, 200, 230),
}


def garment_image(
    category: str,
    colour: str,
    seed: int = 0,
    *,
    lighting: float = 1.0,
    occlusion: float = 0.0,
    background: tuple[int, int, int] | None = None,
    size: int = 64,
) -> tuple[np.ndarray, dict]:
    """Render one synthetic garment photo and its attributes.

    ``lighting`` scales exposure, ``occlusion`` covers that fraction of the image with a
    plain rectangle (a bag, a hand, another person), and ``background`` replaces the
    default grey wall. Those three knobs are the test-time perturbations the lab measures,
    so they are parameters rather than post-processing applied after the fact.
    """
    if category not in GARMENT_CATEGORIES:
        raise ValueError(f"unknown category {category!r}")
    if colour not in GARMENT_COLOURS:
        raise ValueError(f"unknown colour {colour!r}")

    rng = np.random.default_rng(seed)
    bg = background if background is not None else (
        int(rng.integers(70, 150)), int(rng.integers(70, 150)), int(rng.integers(70, 150))
    )
    canvas = np.full((size, size, 3), bg, np.uint8)
    # A few background texture lines, so the classifier cannot use "nothing else on screen".
    for _ in range(5):
        x = int(rng.integers(0, size))
        cv2.line(canvas, (x, 0), (x + int(rng.integers(-8, 8)), size),
                 tuple(int(c * 0.85) for c in bg), 1)

    c = _COLOUR_BGR[colour]
    c = tuple(int(min(255, v * lighting)) for v in c)
    m = size // 8  # margin

    if category == "shirt":
        cv2.rectangle(canvas, (m + 6, m + 6), (size - m - 6, size - m), c, -1)
        cv2.rectangle(canvas, (m - 2, m + 8), (m + 8, m + 24), c, -1)
        cv2.rectangle(canvas, (size - m - 8, m + 8), (size - m + 2, m + 24), c, -1)
        cv2.circle(canvas, (size // 2, m + 6), 5, tuple(int(v * 0.8) for v in c), -1)
    elif category == "trousers":
        cv2.rectangle(canvas, (size // 2 - 14, m), (size // 2 + 14, size - m), c, -1)
        cv2.rectangle(canvas, (size // 2 - 14, size // 2), (size // 2 - 2, size - m),
                      tuple(int(v * 0.9) for v in c), -1)
        cv2.rectangle(canvas, (size // 2 + 2, size // 2), (size // 2 + 14, size - m),
                      tuple(int(v * 0.9) for v in c), -1)
    elif category == "jacket":
        cv2.rectangle(canvas, (m, m + 4), (size - m, size - m), c, -1)
        cv2.line(canvas, (size // 2, m + 4), (size // 2, size - m), (30, 30, 30), 2)
        cv2.circle(canvas, (size // 2, m + 10), 3, (240, 240, 240), -1)
        cv2.rectangle(canvas, (m, m + 4), (m + 6, size - m), tuple(int(v * 0.75) for v in c), -1)
    else:  # hat
        cv2.ellipse(canvas, (size // 2, size // 2 + 8), (22, 7), 0, 0, 360, c, -1)
        cv2.rectangle(canvas, (size // 2 - 11, size // 2 - 16), (size // 2 + 11, size // 2 + 8),
                      c, -1)
        cv2.rectangle(canvas, (size // 2 - 11, size // 2 - 2), (size // 2 + 11, size // 2 + 2),
                      tuple(int(v * 0.7) for v in c), -1)

    if occlusion > 0:
        blocks = max(1, int(round(occlusion * 4)))
        for _ in range(blocks):
            bw = int(size * float(rng.uniform(0.15, 0.35)))
            bh = int(size * float(rng.uniform(0.4, 0.8)))
            x = int(rng.integers(0, max(1, size - bw)))
            y = int(rng.integers(0, max(1, size - bh)))
            cv2.rectangle(canvas, (x, y), (x + bw, y + bh),
                          tuple(int(v * 0.55) for v in bg), -1)

    if lighting != 1.0:
        canvas = np.clip(canvas.astype(np.float32) * lighting, 0, 255).astype(np.uint8)
    noise = rng.integers(-6, 7, size=canvas.shape, dtype=np.int16)
    canvas = np.clip(canvas.astype(np.int16) + noise, 0, 255).astype(np.uint8)

    meta = {
        "category": category,
        "colour": colour,
        "lighting": lighting,
        "occlusion": occlusion,
        "seed": seed,
    }
    return canvas, meta


def garment_dataset(n_per_class: int = 30, seed: int = 3) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Balanced garment images with two label axes: ``(images, categories, colours)``."""
    images, cats, cols = [], [], []
    for ci, category in enumerate(GARMENT_CATEGORIES):
        for i in range(n_per_class):
            colour = GARMENT_COLOURS[i % len(GARMENT_COLOURS)]
            img, _ = garment_image(category, colour, seed=seed + ci * 977 + i * 31)
            images.append(cv2.resize(img, (48, 48), interpolation=cv2.INTER_AREA))
            cats.append(ci)
            cols.append(GARMENT_COLOURS.index(colour))
    return (np.asarray(images, dtype=np.float32) / 255.0,
            np.asarray(cats, dtype=np.int64),
            np.asarray(cols, dtype=np.int64))
