def counting_line(cfg: SceneConfig, *, kind: str = "vertical", at: float = 0.55) -> dict:
    """A virtual tripwire and the expected crossing count for the scene.

    A vertical line at ``at`` (fraction of width) is the usual choice for traffic moving
    across the frame. The expected count is computed from the generator's own trajectories,
    so the lab's "counts match ground truth" check is a real check rather than a constant.
    """
    if kind == "vertical":
        x = at * SCENE_W
        p1, p2 = (x, HORIZON_Y * 0.9), (x, SCENE_H * 0.95)
    else:
        y = at * SCENE_H
        p1, p2 = (0.0, y), (float(SCENE_W), y)

    crossings = []
    for veh in cfg.vehicles:
        prev_side = None
        for i in range(cfg.frames):
            x1, y1, x2, y2 = veh.box(i)
            cx = (x1 + x2) / 2
            if kind == "vertical":
                side = 1 if cx > p1[0] else -1
            else:
                side = 1 if (y1 + y2) / 2 > p1[1] else -1
            if prev_side is not None and side != prev_side:
                crossings.append({
                    "track_id": veh.track_id,
                    "class": veh.kind,
                    "frame": i,
                    "direction": "positive" if side > 0 else "negative",
                })
            prev_side = side
    return {
        "kind": kind,
        "p1": [round(float(v), 2) for v in p1],
        "p2": [round(float(v), 2) for v in p2],
        "expected_crossings": crossings,
        "expected_total": len(crossings),
    }


