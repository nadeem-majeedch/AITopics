"""Deterministic synthetic video generators.

Every video in this section is generated by this module, for three reasons:

* **Licence.** No download, no consent question, no redistribution problem: the pixels are
  produced by code in this repository and released with it as CC0-1.0.
* **Ground truth.** The generator knows where every vehicle is, which track it belongs to,
  and when it crosses the counting line, so tracking and counting can be scored exactly
  rather than eyeballed.
* **Reproducibility.** The same seed produces the same frames byte for byte, so a lab can
  assert on numbers and a student can compare their run with the reference run.

The obvious cost: these are *not* photographs. A model trained here learns this renderer's
flat shading, and a detector pretrained on COCO does not transfer to it. That gap is not
hidden - it is measured and discussed in Modules 6 and 14 and in Lab 4, where the same
frames are used to fine-tune a real COCO detector.

Units and conventions:

* frames are BGR ``uint8`` (OpenCV order), shape ``(360, 640, 3)``;
* boxes are ``(x1, y1, x2, y2)`` floats in pixels, origin top-left, as in COCO;
* ``track_id`` is stable for the life of one vehicle in one video and is never reused.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Sequence

import cv2
import numpy as np

SCENE_W, SCENE_H = 640, 360
HORIZON_Y = int(SCENE_H * 0.42)

# Vehicle kinds are the four COCO traffic classes, so a detector's label set maps onto the
# pretrained model's index names without a translation table in the middle of a lab.
KINDS = ("car", "motorcycle", "bus", "truck")

# Colours are BGR. Deliberately mid-to-dark so that a night render still looks like a road
# scene rather than a light source.
VEHICLE_COLOURS = (
    (190, 190, 195),  # silver
    (40, 60, 170),    # red
    (170, 110, 40),   # blue
    (60, 90, 60),     # dark green
    (35, 35, 40),     # near-black
    (210, 220, 225),  # white
)


# ---------------------------------------------------------------------------
# Traffic scenes
# ---------------------------------------------------------------------------


@dataclass
class Vehicle:
    track_id: int
    kind: str
    lane_y: int          # y of the bottom of the wheels
    x: float             # x of the left edge at t=0
    speed: float         # pixels per frame; negative moves left
    colour: tuple[int, int, int]
    length: int
    height: int
    visible_from: int = 0
    visible_to: int = 10 ** 6

    def box(self, frame_index: int) -> tuple[float, float, float, float]:
        left = self.x + self.speed * frame_index
        return (left, self.lane_y - self.height, left + self.length, float(self.lane_y))

    def present(self, frame_index: int) -> bool:
        return self.visible_from <= frame_index < self.visible_to


@dataclass
class SceneConfig:
    """Everything needed to render one video, so the spec itself can be written to JSON."""

    name: str = "day"
    frames: int = 60
    fps: float = 10.0
    condition: str = "day"          # day | dusk | night | rain
    shake: float = 0.0              # pixels of camera shake amplitude
    vehicles: list[Vehicle] = field(default_factory=list)
    seed: int = 0


DEFAULT_LANES = {"far": 196, "mid": 252, "near": 308}


def _vehicle(kind: str, track_id: int, lane_y: int, x: float, speed: float,
             rng: np.random.Generator) -> Vehicle:
    length, height = {
        "car": (104, 50),
        "motorcycle": (58, 46),
        "bus": (196, 74),
        "truck": (176, 82),
    }[kind]
    # +-8% size jitter keeps the detector from learning one exact template per class.
    scale = float(rng.uniform(0.92, 1.08))
    colour = VEHICLE_COLOURS[int(rng.integers(0, len(VEHICLE_COLOURS)))]
    return Vehicle(track_id, kind, lane_y, x, speed, colour,
                   int(length * scale), int(height * scale))


def make_traffic_config(
    *,
    condition: str = "day",
    seed: int = 0,
    frames: int = 60,
    n_vehicles: int = 6,
    direction: str = "both",      # "both", "right", "left"
    shake: float = 0.0,
    name: str | None = None,
) -> SceneConfig:
    """Build a vehicle layout for one video.

    Speeds are chosen so that most vehicles cross the frame during the clip: slow enough
    that tracking has several frames per vehicle, fast enough that line counting has
    something to count. With 60 frames at 10 fps (6 s) a car at 3 px/frame travels 180 px,
    a bit over a quarter of the width, so lanes are staggered by start position.
    """
    rng = np.random.default_rng(seed)
    lanes = list(DEFAULT_LANES.values())
    vehicles: list[Vehicle] = []
    for i in range(n_vehicles):
        lane_y = lanes[i % len(lanes)]
        going_right = direction == "right" or (direction == "both" and i % 2 == 0)
        speed = float(rng.uniform(2.4, 4.6)) * (1 if going_right else -1)
        kind = KINDS[int(rng.integers(0, len(KINDS)))]
        # Starts are placed in a band around the counting line (x = 0.55 * width) sized by
        # how far the vehicle travels during the clip, so nearly every vehicle crosses it
        # once and the counting lab has something to count. Within the band the positions
        # are spread out, so the clip still shows vehicles entering, passing and leaving
        # rather than all appearing at the same moment. Far-lane vehicles are drawn first,
        # so they are the ones that get occluded by nearer traffic.
        line_x = 0.55 * SCENE_W
        travel = abs(speed) * frames
        vehicle = _vehicle(kind, i + 1, lane_y, 0.0, speed, rng)
        # Offset the *centre* of the vehicle from the line, then convert to a left edge:
        # doing it the other way round makes long vehicles (buses, trucks) start with their
        # centre already past the line and visibly fail to cross it.
        offset = float(rng.uniform(0.10, 0.85)) * travel
        vehicle.x = line_x + (offset if not going_right else -offset) - vehicle.length / 2.0
        vehicles.append(vehicle)
    return SceneConfig(
        name=name or condition,
        frames=frames,
        fps=10.0,
        condition=condition,
        shake=shake,
        vehicles=vehicles,
        seed=seed,
    )


def _draw_background(canvas: np.ndarray, cfg: SceneConfig, rng: np.random.Generator) -> np.ndarray:
    """Sky, verge, road, and lane markings for the given lighting condition."""
    h, w = canvas.shape[:2]
    if cfg.condition == "night":
        sky_top, sky_bottom = (18, 16, 22), (46, 38, 38)
        road = (38, 38, 40)
        verge = (22, 30, 24)
        marking = (120, 120, 110)
    elif cfg.condition == "dusk":
        sky_top, sky_bottom = (60, 70, 120), (120, 130, 165)
        road = (70, 70, 74)
        verge = (45, 55, 45)
        marking = (190, 195, 180)
    elif cfg.condition == "rain":
        sky_top, sky_bottom = (120, 120, 125), (150, 150, 150)
        road = (85, 85, 88)
        verge = (60, 70, 60)
        marking = (170, 170, 170)
    else:
        sky_top, sky_bottom = (170, 150, 120), (205, 195, 175)
        road = (98, 96, 94)
        verge = (70, 90, 70)
        marking = (215, 215, 210)

    # Sky gradient. Written row by row because that is the clearest way to show the math.
    for y in range(HORIZON_Y):
        t = y / max(HORIZON_Y - 1, 1)
        canvas[y, :] = [int(sky_top[c] + (sky_bottom[c] - sky_top[c]) * t) for c in range(3)]

    road_top = HORIZON_Y
    road_bottom = int(h * 0.90)
    canvas[road_top:road_bottom, :] = road
    canvas[road_bottom:, :] = verge
    canvas[HORIZON_Y - 6:HORIZON_Y, :] = verge

    # Dashed centre line, plus solid edge lines. Dashes are phase-locked to the frame so
    # the scene does not flicker, but a small per-frame jitter keeps them from being a
    # perfect straight edge the detector could shortcut on.
    mid = (road_top + road_bottom) // 2 + 6
    for x in range(-40, w + 40, 56):
        cv2.rectangle(canvas, (x, mid), (x + 28, mid + 5), marking, -1)
    cv2.line(canvas, (0, road_top + 8), (w, road_top + 8), marking, 2)
    cv2.line(canvas, (0, road_bottom - 4), (w, road_bottom - 4), marking, 2)

    # Asphalt texture: deterministic noise, coarse enough to survive MP4 compression.
    noise = rng.integers(-8, 9, size=(road_bottom - road_top, w, 1), dtype=np.int16)
    patch = np.clip(canvas[road_top:road_bottom].astype(np.int16) + noise, 0, 255).astype(np.uint8)
    canvas[road_top:road_bottom] = patch

    if cfg.condition == "night":
        # Street lamps: a warm glow that makes the night scene noisy rather than merely dark.
        for lx in range(70, w, 210):
            cv2.circle(canvas, (lx, HORIZON_Y - 26), 46, (40, 60, 80), -1)
            cv2.circle(canvas, (lx, HORIZON_Y - 26), 12, (150, 200, 235), -1)
    return canvas


def _draw_vehicle(canvas: np.ndarray, veh: Vehicle, frame_index: int, condition: str) -> None:
    x1, y1, x2, y2 = [int(round(v)) for v in veh.box(frame_index)]
    w, h = x2 - x1, y2 - y1
    if w <= 4 or h <= 4:
        return
    colour = veh.colour
    if condition == "night":
        colour = tuple(int(c * 0.55) for c in colour)
    elif condition == "rain":
        colour = tuple(int(c * 0.85) for c in colour)

    # Shadow first, so the vehicle reads as sitting on the road rather than floating.
    cv2.ellipse(canvas, ((x1 + x2) // 2, y2 - 1), (max(w // 2, 6), max(h // 8, 3)),
                0, 0, 360, (30, 30, 30), -1)

    if veh.kind == "motorcycle":
        body = (x1 + w // 4, y1 + h // 2)
        cv2.rectangle(canvas, body, (x2 - w // 4, y2 - h // 6), colour, -1)
        cv2.circle(canvas, ((x1 + x2) // 2, y1 + h // 3), max(w // 5, 4), (40, 40, 60), -1)
        cv2.circle(canvas, (x1 + w // 6, y2 - 2), max(h // 8, 3), (25, 25, 25), -1)
        cv2.circle(canvas, (x2 - w // 6, y2 - 2), max(h // 8, 3), (25, 25, 25), -1)
        return

    # Body: main rectangle plus a slightly inset roof, which gives the detector a second
    # horizontal edge and stops the class from being one filled box.
    cv2.rectangle(canvas, (x1, y1 + h // 3), (x2, y2 - h // 8), colour, -1)
    roof_inset = int(w * (0.18 if veh.kind == "car" else 0.08))
    roof_top = y1 if veh.kind != "bus" else y1 + h // 8
    cv2.rectangle(canvas, (x1 + roof_inset, roof_top), (x2 - roof_inset, y1 + h // 2),
                  colour, -1)
    glass = (40, 45, 55) if condition != "night" else (25, 30, 40)
    cv2.rectangle(canvas, (x1 + roof_inset + 4, roof_top + 4),
                  (x2 - roof_inset - 4, y1 + h // 2 - 4), glass, -1)

    if veh.kind == "truck":
        # Container behind the cab: a flat panel with a corner block, the visual cue that
        # separates truck from bus at the sizes used here.
        cv2.rectangle(canvas, (x1 + w // 3, y1), (x2, y2 - h // 6), colour, -1)
        cv2.rectangle(canvas, (x1 + w // 3, y1), (x1 + w // 3 + 6, y2 - h // 6), (20, 20, 20), -1)
    if veh.kind == "bus":
        for wx in range(x1 + 10, x2 - 12, max(w // 7, 10)):
            cv2.rectangle(canvas, (wx, y1 + h // 6), (wx + max(w // 12, 6), y1 + h // 2 - 2),
                          glass, -1)

    wheel_r = max(h // 7, 4)
    for wx in (x1 + int(w * 0.18), x2 - int(w * 0.18)):
        cv2.circle(canvas, (wx, y2 - h // 12), wheel_r, (22, 22, 22), -1)

    # Lights: at night they are the strongest cue, so the generator draws them bright.
    if condition in {"night", "dusk"}:
        light_y = y1 + int(h * 0.55)
        direction = 1 if veh.speed >= 0 else -1
        front = x2 - 4 if direction > 0 else x1 + 4
        cv2.circle(canvas, (front, light_y), 4, (215, 235, 250), -1)
        behind = x1 + 4 if direction > 0 else x2 - 4
        cv2.circle(canvas, (behind, light_y), 3, (60, 60, 200), -1)


def _apply_condition(canvas: np.ndarray, cfg: SceneConfig, rng: np.random.Generator,
                     frame_index: int) -> np.ndarray:
    """Post-processing that makes a condition more than a colour change."""
    if cfg.condition == "rain":
        overlay = canvas.copy()
        for _ in range(140):
            x = int(rng.integers(0, canvas.shape[1]))
            y = int(rng.integers(0, canvas.shape[0]))
            length = int(rng.integers(6, 16))
            cv2.line(overlay, (x, y), (x - 4, y + length), (200, 200, 205), 1)
        canvas = cv2.addWeighted(overlay, 0.55, canvas, 0.45, 0)
        canvas = cv2.GaussianBlur(canvas, (3, 3), 0.6)
    return canvas


def render_frame(cfg: SceneConfig, frame_index: int) -> tuple[np.ndarray, list[dict]]:
    """Render one frame and its ground truth.

    Ground truth is reported for every vehicle present, *including* one hidden behind
    another. That is a deliberate choice: a counting system must not lose a vehicle
    because it was occluded for a second, and a lab that only scores visible objects
    would reward a tracker for giving up.
    """
    rng = np.random.default_rng(cfg.seed * 100_003 + frame_index)
    canvas = np.zeros((SCENE_H, SCENE_W, 3), np.uint8)
    canvas = _draw_background(canvas, cfg, rng)

    present = [v for v in cfg.vehicles if v.present(frame_index)]
    # Painter's algorithm: farthest (smallest y) first, nearest last.
    for veh in sorted(present, key=lambda v: v.lane_y):
        _draw_vehicle(canvas, veh, frame_index, cfg.condition)

    objects = []
    boxes = [v.box(frame_index) for v in present]
    for i, veh in enumerate(present):
        x1, y1, x2, y2 = boxes[i]
        area = max((x2 - x1) * (y2 - y1), 1.0)
        occluded = 0.0
        for j, other in enumerate(present):
            if other is veh or other.lane_y <= veh.lane_y:
                continue  # only nearer vehicles can occlude this one
            other_area = max((boxes[j][2] - boxes[j][0]) * (boxes[j][3] - boxes[j][1]), 1.0)
            if other_area < area:
                continue
            ix1, iy1 = max(x1, boxes[j][0]), max(y1, boxes[j][1])
            ix2, iy2 = min(x2, boxes[j][2]), min(y2, boxes[j][3])
            if ix2 > ix1 and iy2 > iy1:
                occluded = max(occluded, (ix2 - ix1) * (iy2 - iy1) / area)
        objects.append({
            "track_id": veh.track_id,
            "class": veh.kind,
            "box": [round(float(v), 2) for v in boxes[i]],
            "occluded": round(min(float(occluded), 1.0), 3),
        })

    if cfg.shake > 0:
        # Smooth camera shake: a low-frequency sinusoid plus jitter, applied to the image
        # and to every ground-truth box so the annotations stay correct.
        dx = cfg.shake * float(np.sin(frame_index * 0.55 + cfg.seed))
        dy = 0.5 * cfg.shake * float(np.cos(frame_index * 0.37 + cfg.seed))
        matrix = np.float32([[1, 0, dx], [0, 1, dy]])
        canvas = cv2.warpAffine(canvas, matrix, (SCENE_W, SCENE_H),
                                borderMode=cv2.BORDER_REPLICATE)
        for obj in objects:
            x1, y1, x2, y2 = obj["box"]
            obj["box"] = [round(x1 + dx, 2), round(y1 + dy, 2),
                          round(x2 + dx, 2), round(y2 + dy, 2)]

    canvas = _apply_condition(canvas, cfg, rng, frame_index)
    return canvas, objects


def render_scene(cfg: SceneConfig) -> list[tuple[np.ndarray, list[dict]]]:
    """Render every frame of a scene, with ground truth per frame."""
    return [render_frame(cfg, i) for i in range(cfg.frames)]


def scene_manifest(cfg: SceneConfig) -> dict:
    """Serialisable description of a rendered video, including per-frame ground truth."""
    frames = []
    for i in range(cfg.frames):
        _, objects = render_frame(cfg, i)
        frames.append({"frame": i, "t_s": round(i / cfg.fps, 3), "objects": objects})
    return {
        "name": cfg.name,
        "condition": cfg.condition,
        "fps": cfg.fps,
        "frames": cfg.frames,
        "width": SCENE_W,
        "height": SCENE_H,
        "shake": cfg.shake,
        "seed": cfg.seed,
        "vehicles": [
            {
                "track_id": v.track_id,
                "class": v.kind,
                "lane_y": v.lane_y,
                "x0": round(v.x, 2),
                "speed_px_per_frame": round(v.speed, 3),
                "length": v.length,
                "height": v.height,
            }
            for v in cfg.vehicles
        ],
        "frames_gt": frames,
    }


