ACTION_CLASSES = ("right", "left", "approach", "depart", "stationary")


def action_clip(kind: str, seed: int = 0, *, n_frames: int = 8, size: int = 64
                ) -> tuple[np.ndarray, dict]:
    """One short grayscale clip of a shape moving with a specific dynamic.

    The clip is built so that *a single frame is ambiguous*:

    * ``right`` and ``left`` differ only in the direction of travel, and the start
      position is drawn from the same distribution for both, so a square at x=32 is
      equally likely to be travelling either way;
    * ``approach`` and ``depart`` pass through the same range of sizes, so one frame at a
      mid size is equally likely to be growing or shrinking;
    * ``stationary`` jitters by a pixel, which is inside the motion a two-frame difference
      cannot separate from slow movement.

    That construction is the whole point of the lab: a per-frame classifier cannot beat
    chance on this dataset, and a model that sees the sequence can.
    """
    if kind not in ACTION_CLASSES:
        raise ValueError(f"unknown action kind {kind!r}")
    rng = np.random.default_rng(seed)
    frames = np.full((n_frames, size, size), 18, np.uint8)

    if kind in {"right", "left"}:
        half = size // 2
        span = size - 16
        if kind == "right":
            x0 = float(rng.uniform(2, span * 0.35))
            step = float(rng.uniform(2.2, 3.4))
        else:
            x0 = float(rng.uniform(span * 0.65, span - 2))
            step = -float(rng.uniform(2.2, 3.4))
        y = float(rng.uniform(half - 10, half + 10))
        side = int(rng.integers(10, 18))
        for i in range(n_frames):
            frame = frames[i]
            cx = int(x0 + step * i) + side // 2
            cv2.rectangle(frame, (cx - side // 2, int(y) - side // 2),
                          (cx + side // 2, int(y) + side // 2), 225, -1)
    elif kind in {"approach", "depart"}:
        lo, hi = 10, 26
        side0 = int(rng.integers(lo, hi))
        if kind == "approach":
            sizes = [side0 + i * 2 for i in range(n_frames)]
        else:
            sizes = [side0 + (n_frames - 1 - i) * 2 for i in range(n_frames)]
        for i, side in enumerate(sizes):
            frame = frames[i]
            c = size // 2
            cv2.rectangle(frame, (c - side // 2, c - side // 2),
                          (c + side // 2, c + side // 2), 225, -1)
    else:  # stationary
        c = size // 2
        side = int(rng.integers(14, 20))
        jx = int(rng.integers(-1, 2))
        jy = int(rng.integers(-1, 2))
        for i in range(n_frames):
            frame = frames[i]
            dx = jx if i % 2 == 0 else -jx
            dy = jy if i % 3 == 0 else -jy
            cv2.rectangle(frame, (c - side // 2 + dx, c - side // 2 + dy),
                          (c + side // 2 + dx, c + side // 2 + dy), 225, -1)

    meta = {
        "action": kind,
        "seed": seed,
        "frames": n_frames,
        "size": size,
        "fps": 10.0,
        "duration_s": round(n_frames / 10.0, 2),
    }
    return frames, meta


def action_dataset(n_per_class: int = 40, seed: int = 7) -> tuple[np.ndarray, np.ndarray, list[str]]:
    """Clips for every action class, as ``(N, T, H, W)`` float32 in ``[0, 1]``."""
    clips, labels = [], []
    for cls_index, kind in enumerate(ACTION_CLASSES):
        for i in range(n_per_class):
            frames, _ = action_clip(kind, seed=seed + 131 * i + 17 * cls_index)
            clips.append(frames)
            labels.append(cls_index)
    x = np.asarray(clips, dtype=np.float32) / 255.0
    return x, np.asarray(labels, dtype=np.int64), list(ACTION_CLASSES)


