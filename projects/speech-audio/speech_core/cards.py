"""Model and dataset cards for audio systems.

A model card is not paperwork. For a voice system it is the only place where the
people affected by the system - speakers, subjects of recordings, callers - can find
out what was trained on them, what the error rates are for their kind of voice, and
what the system must not be used for.

The helper here builds the card as a dictionary, so a lab can fill the measured
numbers in from its own report rather than retyping them, and renders Markdown that
can be published next to the model.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Sequence

REQUIRED_FIELDS: tuple[str, ...] = (
    "name",
    "version",
    "task",
    "intended_use",
    "out_of_scope",
    "training_data",
    "evaluation",
    "limitations",
    "consent_and_rights",
)


def build_model_card(
    name: str,
    task: str,
    intended_use: Sequence[str],
    out_of_scope: Sequence[str],
    training_data: dict,
    evaluation: dict,
    limitations: Sequence[str],
    consent_and_rights: str,
    version: str = "0.1.0",
    licence: str = "code: MIT, generated data: CC0-1.0",
    contact: str = "course maintainers",
) -> dict:
    """Assemble and lightly validate a card. Missing sections are reported, not invented."""
    card = {
        "name": name,
        "version": version,
        "task": task,
        "intended_use": list(intended_use),
        "out_of_scope": list(out_of_scope),
        "training_data": dict(training_data),
        "evaluation": dict(evaluation),
        "limitations": list(limitations),
        "consent_and_rights": consent_and_rights,
        "licence": licence,
        "contact": contact,
    }
    missing = [field for field in REQUIRED_FIELDS if not card.get(field)]
    card["incomplete_fields"] = missing
    return card


def render_markdown(card: dict) -> str:
    """Render a card as Markdown for docs or a model repository."""
    lines = [f"# Model card: {card.get('name', 'unnamed')}", ""]
    lines.append(f"Version `{card.get('version', '?')}` - task: **{card.get('task', '?')}**")
    lines.append("")

    def bullets(title: str, items) -> None:
        lines.append(f"## {title}")
        if isinstance(items, dict):
            for key, value in items.items():
                lines.append(f"- **{key}**: {_fmt(value)}")
        elif isinstance(items, str):
            lines.append(items)
        else:
            for item in items or ["(not documented)"]:
                lines.append(f"- {item}")
        lines.append("")

    bullets("Intended use", card.get("intended_use"))
    bullets("Out of scope - do not use for", card.get("out_of_scope"))
    bullets("Training data", card.get("training_data", {}))
    bullets("Evaluation", card.get("evaluation", {}))
    bullets("Limitations", card.get("limitations"))
    bullets("Consent, rights, and provenance", card.get("consent_and_rights", "(not documented)"))
    lines.append(f"Licence: {card.get('licence', '?')}  ")
    lines.append(f"Contact: {card.get('contact', '?')}")
    if card.get("incomplete_fields"):
        lines.append("")
        lines.append(f"> Incomplete fields: {', '.join(card['incomplete_fields'])}")
    return "\n".join(lines) + "\n"


def _fmt(value) -> str:
    if isinstance(value, float):
        return f"{value:.4f}"
    if isinstance(value, (list, tuple)):
        return ", ".join(str(v) for v in value)
    return str(value)


def save_card(card: dict, path: str | Path) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.suffix == ".md":
        path.write_text(render_markdown(card), encoding="utf-8")
    else:
        path.write_text(json.dumps(card, indent=2) + "\n", encoding="utf-8")
    return path


