def environment_classifier_card(evaluation: dict | None = None) -> dict:
    """Card for the classifier students train in Labs A and B."""
    return build_model_card(
        name="AITopics synthetic environmental-sound classifier",
        task="4-class audio classification (alarm, rain, footsteps, birdsong)",
        intended_use=[
            "Coursework: learning the audio classification workflow end to end",
            "Comparing waveforms, spectrograms, and Mel features on synthetic clips",
        ],
        out_of_scope=[
            "Any safety, security, or medical alerting use",
            "Detecting events in real recordings: the classes are synthesised, not recorded",
            "Speaker identification - this model classifies sounds, not people",
        ],
        training_data={
            "corpus": "synthetic, generated by speech_core.synth.env_sound",
            "sources": "80 base renderings (4 classes x 20 sources), 3 variants each",
            "split": "grouped by source; a source never appears in two splits",
            "licence": "CC0-1.0",
        },
        evaluation=evaluation or {
            "note": "Run lab_a_env_classifier.py to fill in accuracy, per-class recall, and robustness rows.",
        },
        limitations=[
            "Synthetic classes are far cleaner and more separable than field recordings",
            "No overlapping-event evaluation: each clip contains exactly one class",
            "Accuracy on a noisy street is unknown; the robustness suite is the closest proxy",
            "No demographic or accent dimension exists here, because no people were recorded",
        ],
        consent_and_rights=(
            "No human recordings were used. All audio is generated from code with fixed "
            "seeds, so there are no subjects, no consent to obtain, and no personal data "
            "to protect. Applying this pipeline to real recordings would require a lawful "
            "basis, notice to the people recorded, and a data-retention policy."
        ),
    )


def asr_model_card(evaluation: dict | None = None) -> dict:
    """Card for the from-scratch CTC recogniser and its adapted variant."""
    return build_model_card(
        name="AITopics TinyCRNN isolated-word recogniser",
        task="Character-level CTC speech recognition over a six-word vocabulary",
        intended_use=[
            "Coursework: how CTC alignment, decoding, and WER evaluation work",
            "A baseline for the adaptation and latency labs",
        ],
        out_of_scope=[
            "Transcribing real conversations, meetings, or calls",
            "Any language other than the six synthetic command words",
            "Speaker identification or verification",
            "Accessibility, medical, legal, or safety transcription",
        ],
        training_data={
            "corpus": "synthetic formant speech, 24 voices x 6 words x 2 utterances",
            "vocabulary": "yes, no, start, stop, left, right",
            "split": "speaker-disjoint (18 train / 3 val / 3 test voices)",
            "licence": "CC0-1.0",
            "not_used": "Whisper, wav2vec2, or any pretrained checkpoint - this model is trained from scratch",
        },
        evaluation=evaluation or {
            "note": "Run lab_d_wer_evaluation.py to fill in WER, CER, and per-word accuracy.",
        },
        limitations=[
            "Closed vocabulary: an out-of-vocabulary word can only be spelled or dropped",
            "No accent, dialect, child-speech, or disordered-speech evaluation exists",
            "Single-channel, 16 kHz, one speaker at a time",
            "Synthetic voices are easier than human voices; real WER would be higher",
            "Character error rate can look better than word error rate on short words",
        ],
        consent_and_rights=(
            "All training audio is synthesised from code; no speaker donated a recording. "
            "Adapting this recipe to real speech requires documented consent for every "
            "speaker, a licence review of the corpus, and a plan to delete the data on request."
        ),
    )
